/**
 * Generate `.env.example` from the configuration loader.
 *
 * `CONFIG.md` states the rule: *a variable added to the loader without being
 * added there is a bug.* Writing the file by hand makes that rule something
 * somebody has to remember. Generating it makes the bug impossible — the same
 * argument D-45 makes about the database types.
 *
 *   bun run config:example          write it
 *   bun run config:example --check  fail if it is out of date
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { Environment } from '../platform/config';

const TARGET = '.env.example';

const lines: string[] = [
  '# Generated by `bun run config:example`. Do not edit by hand.',
  '#',
  '# Every variable the application reads, with its default where it has one.',
  '# What each means, and which are secret, is in docs/CONFIG.md — the one place',
  '# that explains them.',
  '',
];

for (const [name, schema] of Object.entries(Environment.properties)) {
  const property = schema as { default?: string | number | boolean };
  const required: readonly string[] = Environment.required;
  const optional = property.default !== undefined || !required.includes(name);
  const value = property.default;

  if (value !== undefined) {
    lines.push(`${name}=${String(value)}`);
  } else if (optional) {
    lines.push(`# ${name}=`);
  } else {
    lines.push(`${name}=`);
  }
}

const content = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
  if (current !== content) {
    console.error(`${TARGET} is out of date. Run: bun run config:example`);
    process.exit(1);
  }
  console.log(`${TARGET} matches the loader`);
} else {
  writeFileSync(TARGET, content);
  console.log(`wrote ${TARGET} — ${String(Object.keys(Environment.properties).length)} variables`);
}
