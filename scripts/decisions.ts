/**
 * The decision record, one file per decision (D-344).
 *
 * `docs/decisions/<category>/D-<n>-<slug>.md` holds one decision, headed `# D-<n>. <title>`. The index in
 * `docs/decisions/README.md` is generated from those files, between two markers, and nothing else in that
 * file is: so the index cannot drift from the record, and the prose around it is written by a person.
 *
 *   bun run decision:new <category> <title…>   the next number, from the template, in its category
 *   bun run decisions:index                    rewrite the index
 *   bun run decisions:index -- --check         fail if the index is not what the files say (CI, via check:docs)
 *
 * What a decision must say (an amendment's note, a cost of reversing, no gap in the numbers) is held by
 * `scripts/check-docs.py`, which reads these files as one record.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** The categories, in the order the index lists them, with what belongs in each. */
export const CATEGORIES = [
  ['product', 'What Purlay is, who it is for, its scope, phases and non-goals'],
  [
    'architecture',
    'The stack, layers, protocol, realtime, API shape, the module platform, performance budgets',
  ],
  ['data', 'Schema, migrations, identifiers, storage, retention, export, search'],
  ['security', 'Authentication, sessions, permissions, privacy, tenant isolation, abuse limits'],
  ['web-ui', 'The web client: design system, layout, screens, interaction, accessibility, copy'],
  ['mobile', 'Native clients, push to devices, client versions'],
  [
    'operations',
    'Deploying, self-hosting, configuration, mail delivery, monitoring, running the cloud',
  ],
  [
    'engineering',
    'The repository, CI, tests, coverage, tooling, how documents and decisions are kept',
  ],
  ['integrations', 'GitHub, webhooks, identity providers, mail in and out, alerts from outside'],
] as const satisfies readonly (readonly [string, string])[];

export type Category = (typeof CATEGORIES)[number][0];

export const isCategory = (name: string): name is Category =>
  CATEGORIES.some(([category]) => category === name);

export const RECORD = 'docs/decisions';
const START =
  '<!-- index:start (generated by `bun run decisions:index`; edit the decisions, not this) -->';
const END = '<!-- index:end -->';

export interface Decision {
  readonly number: number;
  readonly title: string;
  readonly category: Category;
  /** The path from the record's directory, as the index links it. */
  readonly path: string;
  /** The day it was decided, where the decision says so. */
  readonly decided: string | undefined;
  /** The decisions its header says it amends or changes. */
  readonly amends: readonly number[];
}

/** A file's name for a decision: `D-7-the-title-in-words.md`. */
export const fileName = (number: number, slug: string): string => `D-${String(number)}-${slug}.md`;

/** A title as a file name: lower case, ASCII, a few words joined by hyphens. */
export const slugOf = (title: string): string =>
  title
    // The dotless ı (and İ) has no decomposition, so it is spelled out before the marks are dropped.
    .replace(/[ıİ]/g, 'i')
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/`/g, '')
    .split(/\s+—\s+|\s+-\s+/)[0]!
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .filter(
      (word) =>
        !['a', 'an', 'the', 'of', 'and', 'is', 'are', 'to', 'in', 'on', 'for'].includes(word),
    )
    .slice(0, 7)
    .join('-');

/** The words a title relates itself to earlier decisions with (`— amends D-3; builds on D-9`). */
const VERBS =
  'amends|supersedes|changes|revises|reverses|lifts|builds on|extends|answers|completes|reversed by';
/** Each relation and the text it governs, up to the next relation, a `;` or a dash. */
const RELATION = new RegExp(`\\b(${VERBS})\\b((?:(?!\\b(?:${VERBS})\\b)[^;—])*)`, 'gi');
/** The relations that change what an earlier decision says, and so belong in its "Amended by". */
const AMENDING = new Set(['amends', 'supersedes', 'changes', 'revises', 'reverses', 'lifts']);

/** Reads one decision file; `undefined` for a file that is not one (the README, the template, the open questions). */
export const parseDecision = (
  category: Category,
  file: string,
  text: string,
): Decision | undefined => {
  const head = /^# D-(\d+)\. (.+)$/m.exec(text);
  if (head === null || !/^D-\d+-/.test(file)) return undefined;
  const title = head[2]!.trim();
  const amends = [
    ...new Set(
      [...title.matchAll(RELATION)]
        .filter((match) => AMENDING.has(match[1]!.toLowerCase()))
        .flatMap((match) => [...match[2]!.matchAll(/D-(\d+)/g)].map((number) => Number(number[1]))),
    ),
  ];
  // Only a day the decision says it was decided on: the first date in its text may be when it was amended.
  const decided = /\*\*Decided[^*]*?(\d{4}-\d{2}-\d{2})/.exec(text)?.[1];
  return { number: Number(head[1]), title, category, path: `${category}/${file}`, decided, amends };
};

/** Every decision under a record directory, in number order. */
export const readRecord = (root: string): readonly Decision[] =>
  CATEGORIES.flatMap(([category]) => {
    const directory = join(root, category);
    if (!existsSync(directory)) return [];
    return readdirSync(directory)
      .filter((file) => file.endsWith('.md'))
      .map((file) => parseDecision(category, file, readFileSync(join(directory, file), 'utf8')))
      .filter((decision): decision is Decision => decision !== undefined);
  }).toSorted((first, second) => first.number - second.number);

/** The cell for a title: the header without its `amends …` tail, which the last column says. */
const shortTitle = (title: string): string =>
  title.replace(new RegExp(`\\s+—\\s+(?:${VERBS})\\b.*$`, 'i'), '').replace(/\|/g, '\\|');

/** The generated index: a table per category, each row linking its file and naming what amended it. */
export const renderIndex = (decisions: readonly Decision[]): string => {
  const amendedBy = new Map<number, number[]>();
  for (const decision of decisions) {
    for (const amended of decision.amends)
      amendedBy.set(amended, [...(amendedBy.get(amended) ?? []), decision.number]);
  }
  const sections = CATEGORIES.map(([category, about]) => {
    const rows = decisions
      .filter((decision) => decision.category === category)
      .map((decision) => {
        const later = (amendedBy.get(decision.number) ?? [])
          .map((number) => `D-${String(number)}`)
          .join(', ');
        return `| [D-${String(decision.number)}](${decision.path}) | ${shortTitle(decision.title)} | ${decision.decided ?? ''} | ${later} |`;
      });
    return [
      `### ${category} (${String(rows.length)})`,
      '',
      about,
      '',
      '| Decision | Title | Decided | Amended by |',
      '|---|---|---|---|',
      ...rows,
    ].join('\n');
  });
  return [
    START,
    '',
    `${String(decisions.length)} decisions.`,
    '',
    ...sections.flatMap((section) => [section, '']),
    END,
  ].join('\n');
};

/** The README with its index replaced; the prose around the markers is left as it is. */
export const withIndex = (readme: string, index: string): string => {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start)
    throw new Error(`${RECORD}/README.md has lost its index markers`);
  return readme.slice(0, start) + index + readme.slice(end + END.length);
};

/** The repository README's count of decisions (`— 344 decisions`), which `check:docs` holds to the record. */
export const withCount = (readme: string, count: number): string =>
  readme.replace(/— \d+ decisions/, `— ${String(count)} decisions`);

/** The next number: one past the highest there is, so numbering never has a gap. */
export const nextNumber = (decisions: readonly Decision[]): number =>
  decisions.reduce((highest, decision) => Math.max(highest, decision.number), 0) + 1;

/** A new decision's file, from the template, with what `check-docs.py` holds every decision to. */
export const draft = (number: number, title: string, today: string): string =>
  readFileSync(join(RECORD, '_template.md'), 'utf8')
    .replace('D-NNN', `D-${String(number)}`)
    .replace('TITLE', title)
    .replace('YYYY-MM-DD', today);

if (import.meta.main) {
  const [command, ...rest] = process.argv.slice(2);
  const decisions = readRecord(RECORD);
  const readmePath = join(RECORD, 'README.md');
  if (command === 'index') {
    const readme = readFileSync(readmePath, 'utf8');
    const updated = withIndex(readme, renderIndex(decisions));
    if (rest.includes('--check')) {
      if (updated !== readme) {
        console.error(
          `${readmePath} is out of date: run \`bun run decisions:index\` and commit it.`,
        );
        process.exit(1);
      }
      console.log(`decisions index: ${String(decisions.length)} decisions, up to date`);
    } else {
      writeFileSync(readmePath, updated);
      console.log(`decisions index: wrote ${String(decisions.length)} decisions`);
    }
  } else if (command === 'new') {
    const [category, ...words] = rest;
    const title = words.join(' ').trim();
    if (category === undefined || !isCategory(category) || title === '') {
      console.error(
        `usage: bun run decision:new <${CATEGORIES.map(([name]) => name).join('|')}> <title…>`,
      );
      process.exit(1);
    }
    const number = nextNumber(decisions);
    const path = join(RECORD, category, fileName(number, slugOf(title)));
    mkdirSync(join(RECORD, category), { recursive: true });
    writeFileSync(path, draft(number, title, new Date().toISOString().slice(0, 10)));
    const record = readRecord(RECORD);
    writeFileSync(readmePath, withIndex(readFileSync(readmePath, 'utf8'), renderIndex(record)));
    writeFileSync('README.md', withCount(readFileSync('README.md', 'utf8'), record.length));
    console.log(path);
  } else {
    console.error('usage: bun scripts/decisions.ts index [--check] | new <category> <title…>');
    process.exit(1);
  }
}
